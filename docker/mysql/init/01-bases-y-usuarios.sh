#!/bin/bash
# Primer arranque del contenedor: bases de datos y usuarios de Laravel.
# Los permisos de web y gestion se dan después de migrar.

mysql -uroot -p"$MYSQL_ROOT_PASSWORD" <<SQL
CREATE DATABASE IF NOT EXISTS \`$DB_DATABASE\`
    CHARACTER SET utf8mb4 COLLATE utf8mb4_spanish_ci;
CREATE DATABASE IF NOT EXISTS \`$DB_BASE_PRUEBAS\`
    CHARACTER SET utf8mb4 COLLATE utf8mb4_spanish_ci;

CREATE USER IF NOT EXISTS '$DB_ADMIN_USUARIO'@'%' IDENTIFIED BY '$DB_ADMIN_CONTRASENA';
CREATE USER IF NOT EXISTS '$DB_WEB_USUARIO'@'%' IDENTIFIED BY '$DB_WEB_CONTRASENA';
CREATE USER IF NOT EXISTS '$DB_GESTION_USUARIO'@'%' IDENTIFIED BY '$DB_GESTION_CONTRASENA';

GRANT ALL PRIVILEGES ON \`$DB_DATABASE\`.* TO '$DB_ADMIN_USUARIO'@'%';
GRANT ALL PRIVILEGES ON \`$DB_BASE_PRUEBAS\`.* TO '$DB_ADMIN_USUARIO'@'%';
SQL
